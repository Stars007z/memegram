fun langNativeName(langCode: String): String = when (langCode) {
    "en" -> "English"
    "ru" -> "Русский"
    "de" -> "Deutsch"
    "fr" -> "Français"
    "es" -> "Español"
    "zh" -> "中文"
    "ar" -> "العربية"
    "pt" -> "Português"
    "it" -> "Italiano"
    "ja" -> "日本語"
    "ko" -> "한국어"
    "tr" -> "Türkçe"
    "hi" -> "हिन्दी"
    "uk" -> "Українська"
    "pl" -> "Polski"
    "nl" -> "Nederlands"
    "sv" -> "Svenska"
    "da" -> "Dansk"
    "fi" -> "Suomi"
    "no" -> "Norsk"
    "cs" -> "Čeština"
    "ro" -> "Română"
    "hu" -> "Magyar"
    "el" -> "Ελληνικά"
    "th" -> "ไทย"
    "vi" -> "Tiếng Việt"
    "id" -> "Bahasa Indonesia"
    "ms" -> "Bahasa Melayu"
    else -> langCode.uppercase()
}

fun translationIndicator(fromLang: String): String {
    return "\uD83C\uDF10${langToFlag(fromLang)}"
}
